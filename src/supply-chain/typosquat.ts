const POPULAR = new Set<string>(POPULAR_PACKAGES);

/** Optimal string alignment distance (Levenshtein plus adjacent transpositions). */
export function editDistance(a: string, b: string, limit = 3): number {
    if (Math.abs(a.length - b.length) > limit) return limit + 1;
    const rows = Array.from({ length: a.length + 1 }, (_, i) =>
        Array.from({ length: b.length + 1 }, (_, j) => (i === 0 ? j : j === 0 ? i : 0))
    );
    for (let i = 1; i <= a.length; i++) {
        for (let j = 1; j <= b.length; j++) {
            const cost = a[i - 1] === b[j - 1] ? 0 : 1;
            rows[i][j] = Math.min(
                rows[i - 1][j] + 1,
                rows[i][j - 1] + 1,
                rows[i - 1][j - 1] + cost
            );
            if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1])
                rows[i][j] = Math.min(rows[i][j], rows[i - 2][j - 2] + 1);
        }
    }
    return rows[a.length][b.length];
}

const normalize = (name: string) =>
    name
        .toLowerCase()
        .replace(/[-_.]/g, '')
        .replace(/(?:js|node)$/, '');

/** Return the popular package a name appears to imitate, if any. */
export function typosquatTarget(name: string): string | undefined {
    const candidate = name.toLowerCase();
    if (POPULAR.has(candidate)) return undefined;
    const scoped = candidate.startsWith('@');
    const [scope, bare] = scoped ? candidate.slice(1).split('/') : ['', candidate];
    for (const popular of POPULAR_PACKAGES) {
        if (popular.startsWith('@') !== scoped) continue;
        const [realScope, target] = scoped ? popular.slice(1).split('/') : ['', popular];
        if (scoped) {
            // Same package name under a misspelled scope, or a misspelled name in the real scope.
            if (bare === target && realScope.length >= 5 && editDistance(scope, realScope, 2) <= 2)
                return popular;
            if (scope === realScope && target.length >= 4 && editDistance(bare, target, 1) <= 1)
                return popular;
            continue;
        }
        if (target.length < 4) continue;
        if (normalize(bare) === normalize(target) && normalize(target).length >= 4) return popular;
        const limit = target.length >= 8 ? 2 : 1;
        if (editDistance(bare, target, limit) <= limit) return popular;
    }
    return undefined;
}
